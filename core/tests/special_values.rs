#[test]
fn special_values() {
    let mut bad = Vec::new();
    for (src, want, tol) in cases() {
        match eval_constant(src) {
            Ok(v) => {
                let scale = if want == 0.0 { 1.0 } else { want.abs() };
                if !((v - want).abs() <= tol * scale) {
                    bad.push(format!("{src} = {v:.17e}（期待 {want:.17e}、相対誤差 {:.1e}）", (v - want).abs() / scale));
                }
            }
            Err(e) => bad.push(format!("{src}: 誤り {e}")),
        }
    }
    assert!(bad.is_empty(), "{} 個がずれた:\n{}", bad.len(), bad.join("\n"));
}
